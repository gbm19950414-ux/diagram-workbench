test('v2 hierarchy, shared block, edges and evidence validate without changing v1',t=>{
  const {dir,model,manifest}=fixture(t);
  assert.equal(validateDomainModel(model,manifest,dir).elements.archive[0],'guide');
  manifest.sources.guide.location='';assert.equal(validateDomainModel(model,manifest,dir).elements.archive[0],'guide');
  const rootView=selectHierarchyView(model,'archive');
  assert.deepEqual(rootView.nodes.map(n=>n.id),['intake','retrieval']);
  assert.deepEqual(rootView.edges.map(e=>e.id),['topic-link']);
  const block=selectHierarchyView(model,'sorting','source');
  assert.deepEqual(block.nodes.map(n=>n.id),['request','queue','note']);
  assert.deepEqual(block.edges.map(e=>e.id),['flow','compare','loop']);
  assert.equal(block.owned.has('note'),false);
  assert.equal(block.owned.has('queue'),true);
  const related=selectHierarchyView(model,'shared','source');
  assert.equal(related.nodes.some(n=>n.id==='request'),true);
  assert.equal(related.owned.has('request'),false);
  assert.deepEqual(selectHierarchyView(model,'sorting','all').edges.map(e=>e.id),['flow','compare','loop','guess']);
});
